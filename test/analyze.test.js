test("resultsTableFor adds header for bench 1 and markers for bench 3", () => {
  const avgs = Object.fromEntries(SERVERS.map((s, i) => [s, 100 + i]));
  const lats = Object.fromEntries(SERVERS.map((s, i) => [s, 1 + i]));
  const table1 = resultsTableFor(1, avgs, lats);
  assert.ok(table1.startsWith("<!-- PERFORMANCE_RESULTS_START -->\n\n| Query | Server | Requests/sec | Latency (ms) | Relative |"));
  assert.ok(table1.includes("| 1 | `{ posts { id userId title user { id name email}}}` |"));

  const table3 = resultsTableFor(3, avgs, lats);
  assert.ok(table3.startsWith("| 3 | `{ greet }` |"));
  assert.ok(table3.endsWith("\n\n<!-- PERFORMANCE_RESULTS_END -->"));
});

// End-to-end: drive analyze.js exactly like CI does — one invocation per
// benchmark, without gnuplot.
test("analyze.js end-to-end writes results.md, updates README and cleans up", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "e2e-"));
  const cwd = process.cwd();
  process.chdir(dir);

  const allFiles = [];
  for (const bench of [1, 2, 3]) {
    for (const [idx, server] of SERVERS.entries()) {
      const base = (idx + 1) * 100;
      for (let run = 1; run <= 3; run++) {
        const file = `bench${bench}_result${run}_graphql_${server}_run.sh.txt`;
        fs.writeFileSync(file, wrkOutput(String(base + run * 2), `${(idx + 1) + (run - 1) * 0.01}`));
        allFiles.push(file);
      }
    }
  }
  fs.writeFileSync("README.md", "# Benchmarks\n\n<!-- PERFORMANCE_RESULTS_START -->\nold content\n<!-- PERFORMANCE_RESULTS_END -->\n");

  const avgs = Object.fromEntries(SERVERS.map((s, i) => [s, (i + 1) * 100 + 4]));
  const lats = Object.fromEntries(SERVERS.map((s, i) => [s, (i + 1) + 0.01]));
  const benchFiles = (bench) => allFiles.filter((f) => f.startsWith(`bench${bench}`));

  for (const bench of [1, 2, 3]) {
    const result = spawnSync(process.execPath, [path.join(cwd, "analyze.js"), ...benchFiles(bench)], {
      env: { ...process.env, ANALYZE_SKIP_PLOT: "1" },
      encoding: "utf8",
    });
    assert.strictEqual(result.status, 0, `analyze.js bench${bench} failed: ${result.stderr}`);
  }

  try {
    const resultsMd = fs.readFileSync("results.md", "utf8");
    const expectedFirst = [
      "<!-- PERFORMANCE_RESULTS_START -->",
      "",
      "| Query | Server | Requests/sec | Latency (ms) | Relative |",
      "|-------:|--------:|--------------:|--------------:|---------:|",
      "| 1 | `{ posts { id userId title user { id name email}}}` |",
      "|| [GraphQL JIT] | `804.00` | `8.01` | `7.73x` |",
      "|| [Hasura] | `704.00` | `7.01` | `6.77x` |",
      "|| [async-graphql] | `604.00` | `6.01` | `5.81x` |",
      "|| [Tailcall] | `504.00` | `5.01` | `4.85x` |",
      "|| [Gqlgen] | `404.00` | `4.01` | `3.88x` |",
      "|| [Netflix DGS] | `304.00` | `3.01` | `2.92x` |",
      "|| [Caliban] | `204.00` | `2.01` | `1.96x` |",
      "|| [Apollo GraphQL] | `104.00` | `1.01` | `1.00x` |",
    ].join("\n");
    const bench2Rows = resultsTableFor(2, avgs, lats);
    const bench3Rows = resultsTableFor(3, avgs, lats);
    const expectedMd = expectedFirst + "\n" + bench2Rows + "\n" + bench3Rows + "\n";
    assert.strictEqual(resultsMd, expectedMd);

    const readme = fs.readFileSync("README.md", "utf8");
    assert.ok(readme.includes(resultsMd.trimEnd()), "README should contain the new results table");
    assert.ok(!readme.includes("old content"), "README marker block should be replaced");

    for (const file of allFiles) {
      assert.strictEqual(fs.existsSync(file), false, `${file} should be deleted`);
    }
  } finally {
    process.chdir(cwd);
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

test("analyze.js fails loudly when a result file is missing", () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "missing-"));
  const cwd = process.cwd();
  process.chdir(dir);
  try {
    const result = spawnSync(process.execPath, [path.join(cwd, "analyze.js"), "ghost.txt"], {
      env: { ...process.env, ANALYZE_SKIP_PLOT: "1" },
      encoding: "utf8",
    });
    assert.strictEqual(result.status, 1);
    assert.ok(result.stderr.includes("Missing result files: ghost.txt"));
  } finally {
    process.chdir(cwd);
    fs.rmSync(dir, { recursive: true, force: true });
  }
});
